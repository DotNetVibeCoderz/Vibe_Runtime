//! An 8x8 bitmap font for printable ASCII.
//!
//! The reference implementation this crate was ported from uses the `font8x8`
//! crate. This workspace has no external dependencies, so the glyphs live here
//! — 128 entries of 8 bytes, 1 KB of `.rodata`, which is affordable even on
//! the 96 KB board.
//!
//! **Bit 0 is the leftmost column**, matching the order [`crate::fb`] walks a
//! row. Codes below 0x20 and above 0x7E are blank rather than absent, so a
//! lookup never needs a bounds check and a control character in a string
//! leaves a gap instead of a wrong glyph.
//!
//! The test at the bottom renders the table back to text, so a wrong byte
//! shows up as a misshapen letter rather than as a number nobody can check.

