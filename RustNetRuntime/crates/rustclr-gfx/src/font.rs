/// The glyph for a character; blank for anything outside ASCII.
///
/// Non-ASCII is blank rather than a substitute box. A device that drew a `?`
/// where a degree sign belongs is displaying a wrong reading; a gap is at
/// least visibly a gap.
#[inline]
pub fn glyph(c: char) -> &'static [u8; 8] {
    let code = c as u32;
    if code < 128 {
        &FONT_8X8[code as usize]
    } else {
        &FONT_8X8[0]
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Renders a glyph the way the framebuffer would, as text.
    fn render(c: char) -> alloc::string::String {
        let mut out = alloc::string::String::new();
        for row in glyph(c) {
            for col in 0..8 {
                out.push(if row & (1 << col) != 0 { 'X' } else { '.' });
            }
            out.push('\n');
        }
        out
    }

    #[test]
    fn a_letter_looks_like_itself() {
        // `A`: a peak, then a crossbar, then two uprights. Reading the table
        // as numbers proves nothing; reading it as a picture proves this.
        assert_eq!(
            render('A'),
            "..XX....\n\
             .XXXX...\n\
             XX..XX..\n\
             XX..XX..\n\
             XXXXXX..\n\
             XX..XX..\n\
             XX..XX..\n\
             ........\n"
                .replace(' ', "")
        );
    }

    #[test]
    fn space_is_blank_and_letters_are_not() {
        assert!(glyph(' ').iter().all(|row| *row == 0));
        for c in ['A', 'z', '0', '?', '@'] {
            assert!(glyph(c).iter().any(|row| *row != 0), "{c} is blank");
        }
    }

    /// Every printable character must have its own shape. A copy-paste slip in
    /// a 128-entry table is invisible until two letters render the same.
    #[test]
    fn every_printable_glyph_is_distinct() {
        let mut seen: alloc::vec::Vec<(char, [u8; 8])> = alloc::vec::Vec::new();
        for code in 0x21u8..=0x7E {
            let c = code as char;
            let g = *glyph(c);
            if let Some((other, _)) = seen.iter().find(|(_, s)| *s == g) {
                panic!("`{c}` renders the same as `{other}`");
            }
            seen.push((c, g));
        }
    }

    #[test]
    fn nothing_outside_ascii_reaches_the_table() {
        assert!(glyph('\u{00e9}').iter().all(|row| *row == 0));
        assert!(glyph('\u{1F600}').iter().all(|row| *row == 0));
    }
}
